def transcript_icons() -> dict[str, str]:
    """Each icon the transcript JS draws, rendered by ``{% icon %}`` at the size of a step row."""
    return {name: icon(name, "h-3.5 w-3.5") for name in sorted(TRANSCRIPT_ICONS)}


